package org.dinky.sandbox.socket;

/**
 * Checks a session token presented during the Sandbox Socket handshake.
 */
@FunctionalInterface
public interface SandboxSessionChecker {

    /**
     * @param sessionToken token sent by the client during the handshake
     * @return true when the token belongs to a valid login session (or an equivalent configured token)
     */
    boolean accept(String sessionToken);
}
